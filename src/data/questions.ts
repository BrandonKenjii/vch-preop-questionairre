// Single source of truth for the wizard: the full question schema for all
// sections of the VCH pre-operative questionnaire (VCH.0749-TRIAL).
// Field mapping lives separately in fieldMap.ts.

export type QuestionType =
  | "yesno"
  | "number"
  | "text"
  | "bmi"
  | "choice"
  | "multichoice"
  | "group";

/** Input affordance for text questions beyond a plain text box. */
export type TextInputKind = "date" | "tel" | "email" | "digits";

export interface ShowIf {
  questionId: string;
  /** Answer must equal this value (or be a member of this array). */
  equals?: unknown;
  /** Answer must NOT equal this value. */
  notEquals?: unknown;
}

export interface Question {
  /** Stable key, mirrored by fieldMap.ts. */
  id: string;
  /** Section id, e.g. "anesthesia". */
  section: string;
  type: QuestionType;
  label: string;
  required: boolean;
  showIf?: ShowIf;
  /**
   * Render the question even while its showIf condition is unanswered
   * ("soft", enabled but not required) and gray it out (disabled) when the
   * topmost condition in its showIf chain answers No. Used for the blood
   * thinner and infection follow-up lists, which the paper form prints in
   * full.
   */
  grayOut?: boolean;
  /** Group id for numeric subtotals (functional status, PCS). */
  numberGroup?: string;
  /** Option labels for choice/multichoice questions. */
  options?: string[];
  /** Stored values for each option (defaults to the labels themselves). */
  optionValues?: (string | number)[];
  /** Small helper text rendered under the label. */
  hint?: string;
  /** Render text questions as a multiline textarea. */
  multiline?: boolean;
  /** Render text questions as a specialized input (date, phone, email…). */
  input?: TextInputKind;
  /** Placeholder shown before the patient types (defaults per input kind). */
  placeholder?: string;
  /** Numeric bounds for number questions. */
  min?: number;
  max?: number;
  step?: number;
}

export interface Section {
  id: string;
  title: string;
  subtitle?: string;
}

export interface BmiAnswer {
  height: string; // as entered
  heightUnit: "cm" | "ftin";
  feet?: string; // when heightUnit === "ftin"
  inches?: string; // when heightUnit === "ftin"
  weight: string; // as entered
  weightUnit: "kg" | "lbs";
}

export type Answer = boolean | number | string | string[] | BmiAnswer;
export type Answers = Record<string, Answer | undefined>;

